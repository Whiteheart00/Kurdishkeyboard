/**
 * Normalizes Kurdish Sorani / Arabic / Persian character variants so typing
 * e.g. "ھاو" matches "هاوڕێ", "تەنھا" matches "تەنها", "سل" matches "سڵاو" & "سلێمانی",
 * and "كورد" matches "کوردستان".
 */
export function normalizeForPrediction(raw: string): string {
  return raw
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670\u0640]/g, '') // strip harakat & tatweel
    .replace(/[\u06BE\u0629\u06D5\u06C1]/g, 'ه') // ھ ة ە ہ -> ه
    .replace(/[\u064A\u0649\u06CE]/g, 'ی')       // ي ى ێ -> ی
    .replace(/\u0643/g, 'ک')                     // ك -> ک
    .replace(/\u0695/g, 'ر')                     // ڕ -> ر
    .replace(/\u06B5/g, 'ل')                     // ڵ -> ل
    .replace(/[\u06C6\u0624]/g, 'و')             // ۆ ؤ -> و
    .replace(/[\u0622\u0623\u0625]/g, 'ا');      // آ أ إ -> ا
}

// Lightweight 1-edit-distance check for typo tolerance (e.g. "پیتەۆان" -> "پیتەکان")
function isWithinOneEdit(a: string, bPrefix: string): boolean {
  const la = a.length;
  const lb = bPrefix.length;
  if (Math.abs(la - lb) > 1) return false;
  let i = 0;
  let j = 0;
  let edits = 0;
  while (i < la && j < lb) {
    if (a[i] === bPrefix[j]) {
      i++;
      j++;
    } else {
      edits++;
      if (edits > 1) return false;
      if (la > lb) i++;
      else if (lb > la) j++;
      else {
        i++;
        j++;
      }
    }
  }
  if (i < la || j < lb) edits++;
  return edits <= 1;
}

// On-device learned words persistence (100% offline, localStorage)
const LEARNED_WORDS_KEY = 'kurdikebord_learned_words_v1';
const MAX_LEARNED_WORDS = 400;

export function loadLearnedWords(): Record<string, number> {
  try {
    const raw = localStorage.getItem(LEARNED_WORDS_KEY);
    if (!raw) return {};
    const parsed = JSON.parse(raw);
    if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) {
      return parsed as Record<string, number>;
    }
  } catch {
    // ignore storage errors
  }
  return {};
}

export function saveLearnedWords(map: Record<string, number>): void {
  try {
    const entries = Object.entries(map);
    if (entries.length > MAX_LEARNED_WORDS) {
      entries.sort((a, b) => b[1] - a[1]);
      const trimmed = Object.fromEntries(entries.slice(0, MAX_LEARNED_WORDS));
      localStorage.setItem(LEARNED_WORDS_KEY, JSON.stringify(trimmed));
      return;
    }
    localStorage.setItem(LEARNED_WORDS_KEY, JSON.stringify(map));
  } catch {
    // ignore storage errors
  }
}

export function getBaseDictionaryForLang(langCode: string, isLatinLike: boolean): string[] {
  if (langCode === 'ar') return ARABIC_COMMON_WORDS;
  if (langCode === 'fa') return PERSIAN_COMMON_WORDS;
  if (langCode === 'tr') return TURKISH_COMMON_WORDS;
  if (isLatinLike) return ENGLISH_COMMON_WORDS;
  return KURDISH_SORANI_WORDS;
}

export function getNextWordPredictions(
  previousWord: string,
  langCode: string,
  isLatinLike: boolean
): string[] {
  const cleanPrev = previousWord.trim();
  if (!cleanPrev) return [];
  if (isLatinLike) {
    return ENGLISH_NEXT_WORDS[cleanPrev.toLowerCase()] || [];
  }
  if (langCode === 'ar' || langCode === 'fa' || langCode === 'tr') {
    return [];
  }
  const direct = KURDISH_NEXT_WORDS[cleanPrev];
  if (direct) return direct;
  const normPrev = normalizeForPrediction(cleanPrev);
  for (const [k, vals] of Object.entries(KURDISH_NEXT_WORDS)) {
    if (normalizeForPrediction(k) === normPrev) return vals;
  }
  return [];
}

export interface RankedWordEntry {
  word: string;
  norm: string;
}

export function buildIndexedDictionary(words: string[]): RankedWordEntry[] {
  const seen = new Set<string>();
  const out: RankedWordEntry[] = [];
  for (const w of words) {
    const clean = w.trim();
    if (!clean || seen.has(clean)) continue;
    seen.add(clean);
    out.push({ word: clean, norm: normalizeForPrediction(clean) });
  }
  return out;
}

export function queryDictionarySuggestions(
  indexedPool: RankedWordEntry[],
  currentWord: string,
  limit = 6,
  excludeSet?: Set<string>
): string[] {
  const results: string[] = [];
  const seen = new Set<string>(excludeSet ? Array.from(excludeSet) : []);
  const lower = currentWord.toLowerCase();
  const normQuery = normalizeForPrediction(currentWord);

  // Pass 1: Exact raw prefix match (highest priority)
  for (const entry of indexedPool) {
    if (results.length >= limit) return results;
    if (entry.word === currentWord || seen.has(entry.word)) continue;
    if (entry.word.toLowerCase().startsWith(lower)) {
      seen.add(entry.word);
      results.push(entry.word);
    }
  }

  // Pass 2: Normalized Kurdish/Arabic variant prefix match (e.g. "ھاو" -> "هاوڕێ", "تەنھا" -> "تەنها")
  for (const entry of indexedPool) {
    if (results.length >= limit) return results;
    if (entry.word === currentWord || seen.has(entry.word)) continue;
    if (entry.norm.startsWith(normQuery)) {
      seen.add(entry.word);
      results.push(entry.word);
    }
  }

  // Pass 3: Typo / 1-edit-distance prefix correction & substring fallback for words >= 2 chars
  if (results.length < limit && normQuery.length >= 2) {
    for (const entry of indexedPool) {
      if (results.length >= limit) return results;
      if (entry.word === currentWord || seen.has(entry.word)) continue;
      const candidateSlice = entry.norm.slice(0, Math.min(entry.norm.length, normQuery.length));
      if (
        (normQuery.length >= 3 && isWithinOneEdit(normQuery, candidateSlice)) ||
        (entry.norm.length >= normQuery.length + 1 && entry.norm.includes(normQuery))
      ) {
        seen.add(entry.word);
        results.push(entry.word);
      }
    }
  }

  return results;
}
